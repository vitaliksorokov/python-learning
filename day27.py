lyrics = input().split()
word = lyrics.pop(
    0
)  # pop() - метод списков, с помощью которого можно удалить элемент из списка по его индексу и возвращает его
print(lyrics, word, sep="\n")
print(
    "Если индекс в скобках не указан - будет удалён последний элемент списка. Если список пустой или индекс указан за пределами диапазона списка - будет ошибка!"
)
print()
browsers = ["Google", "Yandex", "Yandex", "Mozilla", "Google", "Google"]
cnt1, cnt2, cnt3, cnt4 = (
    browsers.count("Google"),
    browsers.count("Yandex"),
    browsers.count("Mozilla"),
    browsers.count("Firefox"),
)  # count() - метод списков, с помощью которого можно посчитать количество элементов в списке и вернуть их количество
print(cnt1, cnt2, cnt3, cnt4, sep="\n")
print("Если значение в списке не найдено, метод вернет 0!")
