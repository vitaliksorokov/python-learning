lyrics = input().split()
lyrics.reverse()  # reverse() - метод списков, с помощью которого можно инвертировать порядок значений в списке
print(lyrics)
print(
    "reverse()-метод и срез списка[::1] - имеют разные задачи! Метод изменит сам список, а срез - создаст копию списка с противоположным порядком значений!"
)
print()
