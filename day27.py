names = [
    "CHATGPT",
    "GEMINI",
    "GROK",
]  # помимо методов split() и join(), в Python существуют и другие методы для списков
print(names)
names.insert(
    0, 1
)  # insert() - метод списков, с помощью которого можно заменить элемент списка по его индексу на другой (строчный/нестрочный, неважно) и сдвигает предыдущее значение на 1 позицию к концу списка
print(names)
names.insert(4, "Alex")
print(names)
print(
    "Если значение индекса будет выше, чем длина списка, то программа не выдаст ошибку, а добавит новый элемент в конец списка!"
)
print()
names = ["Gvido", "Roman", "Timur"]
position = names.index(
    "Timur"
)  # index() - метод списков, с помощью которого можно найти индекс первого элемента, который нужно найти
print(position)
print(
    "Если элемент в списке не будет найден, то во время выполнения происходит ошибка ValueError!"
)
